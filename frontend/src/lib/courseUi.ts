type Tone = 'blue' | 'amber' | 'rust';

/**
 * `levelColor` dari DB (warisan penamaan Laravel: green/yellow/red)
 * dipetakan ke tone chip pada sistem desain "Tinta & Kertas".
 */
export function levelTone(levelColor: string): Tone {
  switch (levelColor) {
    case 'yellow':
      return 'amber';
    case 'red':
      return 'rust';
    default:
      return 'blue';
  }
}

