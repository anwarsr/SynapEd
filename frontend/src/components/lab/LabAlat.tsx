export function unduh(nama: string, isi: Blob) {
  const url = URL.createObjectURL(isi);
  const a = document.createElement("a");
  a.href = url;
  a.download = nama;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
