export function Kelompok({ children, label }: { children: React.ReactNode; label: string }) {
  return (
    <div role="group" aria-label={label} className="flex items-center gap-0.5 bg-paper-card p-1">
      {children}
    </div>
  );
}

/** Menu tarik-turun sederhana dari <details>; menutup sendiri setelah sebuah tombol di dalamnya diklik. */
export function Menu({ label, ikon, children }: { label: string; ikon: string; children: React.ReactNode }) {
  const ref = useRef<HTMLDetailsElement>(null);
  return (
    <details ref={ref} className="relative">
      <summary className={cn(TOMBOL, "cursor-pointer list-none")}>
        <Ikon d={ikon} />
        <span className="hidden sm:inline">{label}</span>
      </summary>
      <div
        className="absolute left-0 top-full z-40 mt-1 flex w-60 flex-col bg-paper-card p-1 shadow-lift"
        onClick={(e) => {
          if ((e.target as Element).closest("button")) ref.current?.removeAttribute("open");
        }}
      >
        {children}
      </div>
    </details>
  );
}

